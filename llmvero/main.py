from __future__ import annotations

import logging
from contextlib import asynccontextmanager

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from . import __version__
from .api.routes import router
from .config import Settings, get_settings
from .core.pipeline import JobRunner
from .db import Store

log = logging.getLogger("llmvero")


def create_app(settings: Settings | None = None, *, store: Store | None = None, http_client=None) -> FastAPI:
    settings = settings or get_settings()

    @asynccontextmanager
    async def lifespan(app: FastAPI):
        app.state.store = store or Store(settings.db_path)
        app.state.http_client = http_client
        app.state.runner = JobRunner(app.state.store, settings, client=http_client)
        if not settings.access_key:
            log.warning("ACCESS_KEY is empty: the API is open to anyone who can reach it")
        app.state.runner.resume_unfinished()
        yield
        await app.state.runner.shutdown()
        if store is None:
            app.state.store.close()

    app = FastAPI(
        title="LLMvero",
        version=__version__,
        description="Send your app's data, get fine-tuning datasets back, generated by your own model.",
        lifespan=lifespan,
    )
    app.dependency_overrides[get_settings] = lambda: settings
    app.add_middleware(
        CORSMiddleware,
        allow_origins=settings.cors_origins,
        allow_methods=["*"],
        allow_headers=["*"],
    )
    app.include_router(router)

    @app.get("/health", tags=["info"])
    def health() -> dict:
        return {"status": "ok", "version": __version__}

    return app


def app_factory() -> FastAPI:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(name)s: %(message)s")
    return create_app()
